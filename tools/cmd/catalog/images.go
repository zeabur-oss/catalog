package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/zeabur-oss/catalog/tools/internal/catalog"
	"go.yaml.in/yaml/v3"
)

const imagesHeader = "# Generated by `catalog images`. Do not edit.\n"

// imageSet is the images one component renders for one profile.
type imageSet struct {
	// Images are pinned by digest.
	Images []string `yaml:"images" json:"images"`
	// UnpinnedImages have no digest. A release lists them in unpinnedImages.
	UnpinnedImages []string `yaml:"unpinnedImages" json:"unpinnedImages"`
}

// imagesPath is the file that lists the images of component id.
func imagesPath(id string) string { return filepath.Join("images", id+".yaml") }

// images renders every component like render does and writes images/, the
// images each component renders per profile. With -check it writes nothing and
// fails when a file differs.
func images(fs *flag.FlagSet, r *repo) error {
	check := fs.Bool("check", false, "fail when the files differ from the render instead of writing them")
	fs.Parse(os.Args[2:])
	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	comps, err := selectComponents(r.cat, fs.Args())
	if err != nil {
		return err
	}
	return listImages(r.cat, comps, cfg.Versions, *check, len(fs.Args()) == 0)
}

// listImages renders comps and writes their image lists, or with check fails
// on the stale ones. all says comps is every component.
func listImages(cat *catalog.Catalog, comps []*catalog.Component, versions []string, check, all bool) error {
	files := map[string][]byte{}
	var errs []error
	for _, c := range comps {
		sets, err := renderImages(cat, c, versions)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		data, err := marshalImages(sets)
		if err != nil {
			return err
		}
		files[imagesPath(c.ID)] = data
		slog.Info("listed images", "component", c.ID)
	}
	if err := errors.Join(errs...); err != nil {
		return err
	}
	return syncImages(files, check, all)
}

// renderImages renders every release of c for each profile and Kubernetes
// version and returns the union of their images per profile.
func renderImages(cat *catalog.Catalog, c *catalog.Component, versions []string) (map[string]imageSet, error) {
	sets := map[string]imageSet{}
	var errs []error
	for _, rel := range c.Releases {
		extra, err := contributions(cat, c.ID, rel.Name)
		if err != nil {
			return nil, err
		}
		for _, p := range catalog.Profiles {
			if c.Defaults[p] == "unsupported" {
				continue
			}
			set := sets[p]
			for _, kv := range versions {
				manifest, err := catalog.Template(c, rel, p, kv, extra...)
				if err != nil {
					errs = append(errs, fmt.Errorf("%s/%s %s %s: %w", c.ID, rel.Name, p, kv, err))
					continue
				}
				pinned, unpinned := catalog.SplitImages(manifest)
				set.Images = append(set.Images, pinned...)
				set.UnpinnedImages = append(set.UnpinnedImages, unpinned...)
			}
			sets[p] = set
		}
	}
	for p, set := range sets {
		sets[p] = imageSet{Images: sortedUnique(set.Images), UnpinnedImages: sortedUnique(set.UnpinnedImages)}
	}
	return sets, errors.Join(errs...)
}

func sortedUnique(l []string) []string {
	out := slices.Clone(l)
	slices.Sort(out)
	return append([]string{}, slices.Compact(out)...)
}

func marshalImages(sets map[string]imageSet) ([]byte, error) {
	data, err := yaml.Marshal(sets)
	return append([]byte(imagesHeader), data...), err
}

// syncImages writes files, or with check compares them with the disk and names
// the stale ones. With all, a file under images/ that no component owns is
// stale too, and writing removes it.
func syncImages(files map[string][]byte, check, all bool) error {
	var stale []string
	for path, want := range files {
		got, err := os.ReadFile(path)
		if err == nil && bytes.Equal(got, want) {
			continue
		}
		stale = append(stale, path)
		if check {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			return err
		}
	}
	if all {
		err := filepath.WalkDir("images", func(path string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() || files[path] != nil {
				return err
			}
			stale = append(stale, path)
			if check {
				return nil
			}
			return os.Remove(path)
		})
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
	}
	if len(stale) == 0 || !check {
		return nil
	}
	slices.Sort(stale)
	return fmt.Errorf("these image lists are stale; run `catalog images` and commit them:\n  %s", strings.Join(stale, "\n  "))
}

// readImages reads the committed image lists of component c, one per profile
// it supports.
func readImages(c *catalog.Component) (map[string]imageSet, error) {
	data, err := os.ReadFile(imagesPath(c.ID))
	if err != nil {
		return nil, fmt.Errorf("%s: %w; run `catalog images` and commit the result", c.ID, err)
	}
	sets := map[string]imageSet{}
	if err := yaml.Unmarshal(data, &sets); err != nil {
		return nil, fmt.Errorf("%s: %w", imagesPath(c.ID), err)
	}
	for _, p := range catalog.Profiles {
		if _, ok := sets[p]; !ok && c.Defaults[p] != "unsupported" {
			return nil, fmt.Errorf("%s: no %s list; run `catalog images` and commit the result", imagesPath(c.ID), p)
		}
	}
	return sets, nil
}
